const PATHS = {};
for (const [name, rows] of Object.entries(BITMAPS)) {
  let d = "";
  rows.forEach((row, y) => {
    for (const m of row.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`;
  });
  PATHS[name] = d;
}

export function iconSvg(name) {
  return `<svg class="i" viewBox="0 0 11 11" width="11" height="11" shape-rendering="crispEdges" fill="currentColor" aria-hidden="true"><path d="${PATHS[name]}"/></svg>`;
}

export function icon(name) {
  const t = document.createElement("template");
  t.innerHTML = iconSvg(name);
  return t.content.firstChild;
}
