#!/usr/bin/env node
// Regenerate anime/fx/index.js (the registry the live viewer reads) and anime/CATALOG.md from the effect files.
// Writes nothing outside anime/: the main registry, catalog and README are not touched.
//
//   node anime/build-index.mjs

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
process.env.PIXELFX_FX_DIR = join(HERE, "fx");
const { allIds, loadEffect } = await import("../tools/lib/fxlib.mjs");
const { categories } = await import("./fx/categories.js");

const metas = [];
for (const id of allIds()) {
  try {
    metas.push({ id, ...(await loadEffect(id)).meta });
  } catch (e) {
    console.error(`skipping ${id}: ${String(e.message ?? e).split("\n")[0]}`);
  }
}
const order = new Map(categories.map((c, i) => [c.id, i]));
const rank = (id) => order.get(id.split("/")[0]) ?? 99;
metas.sort((a, b) => rank(a.id) - rank(b.id) || a.id.localeCompare(b.id));
const ids = metas.map((m) => m.id), ident = (id) => id.replace(/[^a-z0-9]+/gi, "_");

writeFileSync(
  join(HERE, "fx", "index.js"),
  [
    "// Generated by anime/build-index.mjs: every anime effect, by id. Don't edit; run `node anime/build-index.mjs`.",
    "",
    ...ids.map((id) => `import * as ${ident(id)} from "./${id}.js";`),
    "",
    `export { categories } from "./categories.js";`,
    "",
    "export const effects = {",
    ...ids.map((id) => `  "${id}": ${ident(id)},`),
    "};",
    "",
  ].join("\n"),
);

const md = ["# Anime lab catalog", "", `${ids.length} effects. Render any of them with \`node anime/run.mjs render <id> --gif\`.`, ""];
for (const c of categories) {
  const list = metas.filter((m) => m.id.startsWith(c.id + "/"));
  if (!list.length) continue;
  md.push(`## ${c.name}`, "", `${c.blurb}.`, "", "| effect | id | | size | what it does |", "|---|---|---|---|---|");
  for (const m of list) md.push(`| ${m.name} | \`${m.id}\` | ${m.loop ? "loop" : "one-shot"} ${+m.duration.toFixed(2)}s | ${m.size[0]}×${m.size[1]} | ${m.desc.replace(/\|/g, "\\|")} |`);
  md.push("");
}
writeFileSync(join(HERE, "CATALOG.md"), md.join("\n"));
console.log(`${ids.length} effects -> anime/fx/index.js, anime/CATALOG.md`);
