#!/usr/bin/env node
// Measure what each effect really draws, so the gallery can frame the art instead of its canvas and open on its best
// moment. Effects are deterministic, so this only has to run once per change: node tools/framing.mjs
//
// Writes gallery/framing.js (and one per pack): { id: [x0, y0, x1, y1, peakFrame] }, the box around the origin.
// Also writes gallery/manifest.js and gallery/search-index.js, which navigation uses to know about every collection.

import { writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { ROOT } from "./lib/fxlib.mjs";
import { createFrame, clearFrame, createFx, createAct, composite, drawActor, painterFor, stockActor, actorAlphaOf } from "../src/core/index.js";
import { isScreen } from "../gallery/player.js";

const TARGETS = [
  ["src/fx/index.js", "gallery/framing.js"],
  ["dark-fantasy-love/fx/index.js", "dark-fantasy-love/gallery/framing.js"],
  ["attachment-hearts/fx/index.js", "attachment-hearts/gallery/framing.js"],
  ["anime/fx/index.js", "anime/gallery/framing.js"],
  ["anime-sakuga/fx/index.js", "anime-sakuga/gallery/framing.js"],
];
const COLLECTIONS = [
  ["core", "src/fx/index.js"],
  ["dark-fantasy", "dark-fantasy-love/fx/index.js"],
  ["hearts", "attachment-hearts/fx/index.js"],
  ["sanguine", "labs/sanguine-arcana/fx/index.js"],
  ["shonen", "labs/shonen-arts/fx/index.js"],
  ["anime", "anime/fx/index.js"],
  ["sakuga", "anime-sakuga/fx/index.js"],
];
const SAMPLES = 16, SOLID = 48, MARGIN = 3;

function measure(mod) {
  const m = mod.meta, step = 1 / m.fps, [w, h] = m.size, [ox, oy] = m.origin;
  const acted = !!mod.act;
  // an acted effect can travel well outside its own canvas; give it room to be measured
  const W = acted ? w + 480 : w, H = acted ? h + 240 : h, x = acted ? ox + 240 : ox, y = acted ? oy + 120 : oy;
  const frame = createFrame(W, H), data = new Uint8ClampedArray(W * H * 4);
  const inst = (acted ? createAct : createFx)(mod, { x, y });
  const seconds = acted ? (mod.act.poses.at(-1)[0] - mod.act.poses[0][0]) : m.duration;
  const n = Math.max(1, Math.round(seconds * m.fps)), every = Math.max(1, Math.floor(n / SAMPLES));
  let x0 = W, y0 = H, x1 = 0, y1 = 0, best = -1, peak = 0;
  for (let i = 0; i < n; i++) {
    if (i) inst.update(step);
    if (i % every) continue;
    const f = clearFrame(frame);
    if (acted) inst.draw(f);
    else {
      inst.draw(f, "back");
      if (m.actor) drawActor(painterFor(f).place(x, y, false), stockActor(), actorAlphaOf(mod, inst.t, inst.options));
      inst.draw(f, "front");
    }
    composite(f, data, null);
    let ink = 0;
    for (let py = 0; py < H; py++)
      for (let px = 0; px < W; px++) {
        const i = (py * W + px) * 4;
        if (data[i + 3] <= SOLID) continue;
        // a pure white flash is the loudest frame but the least telling one to open on
        if (data[i] < 236 || data[i + 1] < 236 || data[i + 2] < 236) ink++;
        if (px < x0) x0 = px;
        if (px > x1) x1 = px;
        if (py < y0) y0 = py;
        if (py > y1) y1 = py;
      }
    if (ink > best) {
      best = ink;
      peak = i;
    }
  }
  if (x1 <= x0 || y1 <= y0) return [-ox, -oy, w - ox, h - oy, peak];
  return [x0 - x - MARGIN, y0 - y - MARGIN, x1 - x + MARGIN + 1, y1 - y + MARGIN + 1, peak];
}

for (const [src, out] of TARGETS) {
  if (!existsSync(join(ROOT, src))) continue;
  const { effects } = await import(pathToFileURL(join(ROOT, src)).href);
  const table = {};
  for (const [id, mod] of Object.entries(effects)) {
    table[id] = measure({ ...mod, meta: { fps: 30, loop: false, duration: 1, options: {}, ...mod.meta } });
  }
  const rows = Object.entries(table).map(([id, r]) => `  ${JSON.stringify(id)}: ${JSON.stringify(r)},`);
  writeFileSync(join(ROOT, out), `// Generated by tools/framing.mjs: the box each effect's art uses around its origin, and its fullest frame.\nexport const framing = {\n${rows.join("\n")}\n};\n`);
  console.log(`${out}: ${rows.length} effects`);
}

// What navigation needs without loading any effect: each collection's sections for the instant first paint (manifest),
// and every effect's name and tags for the palette (search index, loaded the first time the palette opens).
const manifest = {}, search = {};
for (const [collection, src] of COLLECTIONS) {
  if (!existsSync(join(ROOT, src))) continue;
  const pack = await import(pathToFileURL(join(ROOT, src)).href);
  const list = Object.entries(pack.effects).map(([id, mod]) => ({ id, cat: id.split("/")[0], mod, meta: { loop: false, duration: 1, tags: [], ...mod.meta } }));
  const cats = (pack.categories ?? pack.groups).filter((c) => list.some((f) => f.cat === c.id));
  manifest[collection] = {
    count: list.length,
    categories: cats.map((c) => {
      const mine = list.filter((f) => f.cat === c.id);
      // n, w or s per tile: the sizes the sheet will lay out, so the first paint already has its final shape
      const cells = mine.map((f) => (isScreen(f) ? "s" : f.mod.act || f.meta.size[0] > 200 || f.meta.size[1] > 170 ? "w" : "n")).join("");
      return { id: c.id, name: c.name, blurb: c.blurb ?? "", count: mine.length, cells };
    }),
  };
  search[collection] = list.map((f) => [f.id, f.meta.name, (f.meta.loop ? 1 : 0) + (f.mod.act ? 2 : 0), +f.meta.duration.toFixed(2), f.meta.tags.join(" ")]);
}
const note = "// Generated by tools/framing.mjs.\n";
writeFileSync(join(ROOT, "gallery/manifest.js"), `${note}export const MANIFEST = ${JSON.stringify(manifest)};\n`);
writeFileSync(join(ROOT, "gallery/search-index.js"), `${note}export const SEARCH = ${JSON.stringify(search)};\n`);
console.log(`gallery/manifest.js and search-index.js: ${Object.values(search).flat().length} effects in ${Object.keys(search).length} collections`);
